import json
import os
import pickle
import time
import re
from collections import defaultdict

# 1. Fungsi untuk membersihkan teks dan melakukan tokenisasi
def preprocess(text):
    if not text:
        return []
    # Mengubah teks ke huruf kecil dan mengambil kata-katanya saja
    tokens = re.findall(r'\b\w+\b', text.lower())
    return tokens

# 2. Fungsi untuk membuat inverted index dari dataset berita
def build_index(dataset_path):
    print("Mulai membangun inverted index...")
    start_time = time.time()

    inverted_index = defaultdict(dict)
    doc_count = 0

    # Membaca file JSON baris per baris
    with open(dataset_path, 'r', encoding='utf-8') as f:
        for line_idx, line in enumerate(f):
            try:
                data = json.loads(line)
                doc_id = line_idx

                # Menggabungkan headline dan deskripsi berita
                headline = data.get('headline', '')
                description = data.get('short_description', '')
                full_text = f"{headline} {description}"

                tokens = preprocess(full_text)

                # Menghitung frekuensi kata di dokumen ini
                term_freqs = defaultdict(int)
                for token in tokens:
                    term_freqs[token] += 1

                # Memasukkan ke dalam inverted index
                for term, freq in term_freqs.items():
                    inverted_index[term][doc_id] = freq

                doc_count += 1
            except json.JSONDecodeError:
                continue

    build_time = time.time() - start_time
    print(f"Selesai! Diproses {doc_count} dokumen dalam {build_time:.2f} detik.")
    return dict(inverted_index)

# 3. Fungsi utama untuk cek file pickle atau build baru
def load_or_build_index(dataset_path, pickle_path="inverted_index.pkl"):
    if os.path.exists(pickle_path):
        print(f"File '{pickle_path}' ditemukan. Memuat index langsung (tanpa build ulang)...")
        start_load = time.time()
        with open(pickle_path, 'rb') as f:
            inverted_index = pickle.load(f)
        load_time = time.time() - start_load
        print(f"Index berhasil dimuat dalam {load_time:.4f} detik.")
        return inverted_index
    else:
        print(f"File '{pickle_path}' belum ada. Membangun index baru...")
        inverted_index = build_index(dataset_path)

        print(f"Menyimpan index ke file '{pickle_path}' dengan pickle...")
        start_save = time.time()
        with open(pickle_path, 'wb') as f:
            pickle.dump(inverted_index, f)
        save_time = time.time() - start_save
        print(f"Index berhasil disimpan dalam {save_time:.2f} detik.")
        return inverted_index

# --- MENJALANKAN PROGRAM ---
DATASET_FILE = "News_Category_Dataset_v3.json"
PICKLE_FILE = "inverted_index.pkl"

# Jalankan fungsi utama
my_index = load_or_build_index(DATASET_FILE, PICKLE_FILE)
print(f"Total kata unik (terms) di dalam index: {len(my_index):,}")